			<p class="dh-kicker dh-rise">Häufige Fragen</p>
			<h2 class="dh-h2 dh-rise" id="h-faq">Gut zu wissen</h2>
		</div>
		<div class="og-faq">
			<details><summary>Muss ein Team besonders humorvoll sein?</summary><div>Nein. Es geht nicht darum, wer am lustigsten ist. Es geht darum zu verstehen, wie Humor im eigenen Team wirkt. Dazu gehört auch, Zurückhaltung und unterschiedliche Vorlieben ernst zu nehmen.</div></details>
			<details><summary>Geht es in den Trainings darum, mehr Witze zu machen?</summary><div>Nein. Im Mittelpunkt steht, was Humor in einer Situation tut: ob er verbindet, entlastet, Status markiert oder verletzt. Daraus entstehen bewusstere Entscheidungen, mal für Humor und mal dagegen.</div></details>
			<details><summary>Wie werden Grenzen und unterschiedliche Reaktionen auf Humor berücksichtigt?</summary><div>Unterschiedliche Reaktionen sind Teil des Themas, kein Störfaktor. Die Formate arbeiten mit Fragen zu Ziel, Publikum, Beziehung, Macht und Situation. Niemand muss sich beteiligen, wenn es sich nicht richtig anfühlt, und Humor auf Kosten Einzelner ist kein Übungsmaterial.</div></details>
			<details><summary>Können Inhalte an eine konkrete Führungs- oder Teamsituation angepasst werden?</summary><div>Ja. Im Vorgespräch klären wir Anliegen, Zielgruppe und Rahmen. Darauf werden Inhalte, Beispiele und Übungen abgestimmt.</div></details>
			<details><summary>Was, wenn Humor im Team gerade ein heikles Thema ist?</summary><div>Gerade dann kann es sinnvoll sein, darüber zu sprechen. Die Formate rücken Wirkung und Grenzen in den Mittelpunkt, nicht Pointen. Im Vorgespräch klären wir, was aktuell im Team los ist und wie behutsam der Einstieg sein sollte.</div></details>
			<details><summary>Welche Formate sind verfügbar?</summary><div><p>Keynote oder Impulsvortrag, Workshop oder Teamtraining, maßgeschneidertes Business-Training und Coaching für Führungskräfte oder Einzelpersonen.</p><p>Alle Formate sind online oder in Präsenz möglich, bevorzugt in Präsenz. Dauer, Gruppengröße und Ablauf stimmen wir passend zu Ihrem Anliegen und Format ab. Coaching kann auch über Ihre Organisation gebucht werden.</p></div></details>

			<details><summary>Does a team have to be particularly funny?</summary><div>No. It is not about who is the funniest. It is about understanding how humour works in your own team. That includes taking reticence and different preferences seriously.</div></details>
			<details><summary>Is the training about making more jokes?</summary><div>No. The focus is on what humour does in a situation: whether it connects, eases tension, signals status or hurts. That leads to more conscious decisions, sometimes in favour of humour and sometimes against it.</div></details>
			<details><summary>How are limits and different reactions to humour taken into account?</summary><div>Different reactions are part of the topic, not a disruption. The formats work with questions about aim, audience, relationship, power and situation. Nobody has to take part if it does not feel right, and humour at the expense of individuals is not practice material.</div></details>
			<details><summary>Can the content be adapted to a specific leadership or team situation?</summary><div>Yes. In an initial call, we clarify your needs, the target group and the setting. Content, examples and exercises are then tailored accordingly.</div></details>
